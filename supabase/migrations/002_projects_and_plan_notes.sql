create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  color text not null default 'coral',
  description text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.projects enable row level security;

create policy "Users can view their own projects" on public.projects for select using (auth.uid() = user_id);
create policy "Users can create their own projects" on public.projects for insert with check (auth.uid() = user_id);
create policy "Users can update their own projects" on public.projects for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users can delete their own projects" on public.projects for delete using (auth.uid() = user_id);

grant select, insert, update, delete on public.projects to authenticated;
grant usage, select on sequence public.projects_id_seq to authenticated;

drop trigger if exists set_projects_updated_at on public.projects;
create trigger set_projects_updated_at before update on public.projects for each row execute function public.set_updated_at();

alter table public.tasks add column if not exists project_id bigint references public.projects(id) on delete cascade;
create index if not exists tasks_project_id_idx on public.tasks(project_id);

insert into public.projects (user_id, name, color, description)
select distinct user_id, 'Website launch', 'coral', 'Primary delivery project'
from public.tasks t
where not exists (select 1 from public.projects p where p.user_id = t.user_id);

update public.tasks t
set project_id = p.id
from public.projects p
where t.user_id = p.user_id and t.project_id is null;

do $$ begin
  alter publication supabase_realtime add table public.projects;
exception when duplicate_object then null;
end $$;
