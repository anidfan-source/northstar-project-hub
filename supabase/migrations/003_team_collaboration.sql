create extension if not exists citext;

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  username citext not null unique,
  team_id uuid not null references public.teams(id) on delete restrict,
  must_change_password boolean not null default true,
  created_at timestamptz not null default now()
);

create or replace function public.current_team_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$ select team_id from public.profiles where user_id = auth.uid() $$;

revoke all on function public.current_team_id() from public;
grant execute on function public.current_team_id() to authenticated;

alter table public.projects add column if not exists team_id uuid references public.teams(id) on delete restrict;
alter table public.tasks add column if not exists team_id uuid references public.teams(id) on delete restrict;
alter table public.projects alter column team_id set default public.current_team_id();
alter table public.tasks alter column team_id set default public.current_team_id();

update public.projects p set team_id = pr.team_id from public.profiles pr where p.user_id = pr.user_id and p.team_id is null;
update public.tasks t set team_id = p.team_id from public.projects p where t.project_id = p.id and t.team_id is null;

drop policy if exists "Users can view their own projects" on public.projects;
drop policy if exists "Users can create their own projects" on public.projects;
drop policy if exists "Users can update their own projects" on public.projects;
drop policy if exists "Users can delete their own projects" on public.projects;
create policy "Team members can view projects" on public.projects for select to authenticated using (team_id = public.current_team_id());
create policy "Users can create team projects" on public.projects for insert to authenticated with check (user_id = auth.uid() and team_id = public.current_team_id());
create policy "Owners can update projects" on public.projects for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid() and team_id = public.current_team_id());
create policy "Owners can delete projects" on public.projects for delete to authenticated using (user_id = auth.uid());

drop policy if exists "Users can read their own tasks" on public.tasks;
drop policy if exists "Users can create their own tasks" on public.tasks;
drop policy if exists "Users can update their own tasks" on public.tasks;
drop policy if exists "Users can delete their own tasks" on public.tasks;
create policy "Team members can view tasks" on public.tasks for select to authenticated using (team_id = public.current_team_id());
create policy "Users can create team tasks" on public.tasks for insert to authenticated with check (user_id = auth.uid() and team_id = public.current_team_id());
create policy "Owners can update tasks" on public.tasks for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid() and team_id = public.current_team_id());
create policy "Owners can delete tasks" on public.tasks for delete to authenticated using (user_id = auth.uid());

alter table public.profiles enable row level security;
drop policy if exists "Team members can view profiles" on public.profiles;
create policy "Team members can view profiles" on public.profiles for select to authenticated using (team_id = public.current_team_id());

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  team_id uuid not null default public.current_team_id() references public.teams(id) on delete cascade,
  sender_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.messages enable row level security;
drop policy if exists "Team members can read messages" on public.messages;
drop policy if exists "Team members can send messages" on public.messages;
create policy "Team members can read messages" on public.messages for select to authenticated using (team_id = public.current_team_id());
create policy "Team members can send messages" on public.messages for insert to authenticated with check (sender_id = auth.uid() and team_id = public.current_team_id());

create or replace function public.complete_first_login()
returns void
language sql
security definer
set search_path = public
as $$ update public.profiles set must_change_password = false where user_id = auth.uid() $$;

revoke all on function public.complete_first_login() from public;
grant execute on function public.complete_first_login() to authenticated;
grant select on public.teams to authenticated;
grant select on public.profiles to authenticated;
grant select, insert on public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to authenticated;

do $$ begin
  alter publication supabase_realtime add table public.messages;
exception when duplicate_object then null;
end $$;

notify pgrst, 'reload schema';
