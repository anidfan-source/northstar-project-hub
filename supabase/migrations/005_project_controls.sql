create table if not exists public.raid_items (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  team_id uuid not null default public.current_team_id() references public.teams(id) on delete cascade,
  created_by uuid not null default auth.uid() references auth.users(id),
  kind text not null check (kind in ('Risk','Assumption','Issue','Dependency')),
  title text not null check (char_length(title) between 1 and 200),
  owner text not null default '',
  impact text not null default 'Medium' check (impact in ('Low','Medium','High')),
  status text not null default 'Open' check (status in ('Open','Monitoring','Closed')),
  due_date date,
  mitigation text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.decisions (
  id bigint generated by default as identity primary key,
  project_id bigint not null references public.projects(id) on delete cascade,
  team_id uuid not null default public.current_team_id() references public.teams(id) on delete cascade,
  created_by uuid not null default auth.uid() references auth.users(id),
  title text not null check (char_length(title) between 1 and 200),
  outcome text not null default '',
  decided_by text not null default '',
  decided_at date not null default current_date,
  created_at timestamptz not null default now()
);

create table if not exists public.task_dependencies (
  task_id bigint not null references public.tasks(id) on delete cascade,
  depends_on_task_id bigint not null references public.tasks(id) on delete cascade,
  team_id uuid not null default public.current_team_id() references public.teams(id) on delete cascade,
  created_by uuid not null default auth.uid() references auth.users(id),
  created_at timestamptz not null default now(),
  primary key (task_id, depends_on_task_id),
  check (task_id <> depends_on_task_id)
);

create table if not exists public.task_comments (
  id bigint generated by default as identity primary key,
  task_id bigint not null references public.tasks(id) on delete cascade,
  team_id uuid not null default public.current_team_id() references public.teams(id) on delete cascade,
  author_id uuid not null default auth.uid() references auth.users(id),
  body text not null check (char_length(body) between 1 and 4000),
  created_at timestamptz not null default now()
);

create table if not exists public.activity_events (
  id bigint generated by default as identity primary key,
  team_id uuid not null default public.current_team_id() references public.teams(id) on delete cascade,
  actor_id uuid references auth.users(id),
  project_id bigint references public.projects(id) on delete cascade,
  action text not null,
  entity_type text not null,
  entity_title text not null default '',
  created_at timestamptz not null default now()
);

alter table public.raid_items enable row level security;
alter table public.decisions enable row level security;
alter table public.task_dependencies enable row level security;
alter table public.task_comments enable row level security;
alter table public.activity_events enable row level security;

do $$ declare table_name text; begin
  foreach table_name in array array['raid_items','decisions','task_dependencies','task_comments','activity_events'] loop
    execute format('drop policy if exists "Team read" on public.%I', table_name);
    execute format('drop policy if exists "Team insert" on public.%I', table_name);
    execute format('drop policy if exists "Creator update" on public.%I', table_name);
    execute format('drop policy if exists "Creator delete" on public.%I', table_name);
    execute format('create policy "Team read" on public.%I for select to authenticated using (team_id = public.current_team_id())', table_name);
    execute format('create policy "Team insert" on public.%I for insert to authenticated with check (team_id = public.current_team_id())', table_name);
  end loop;
end $$;

create policy "Creator update" on public.raid_items for update to authenticated using (created_by = auth.uid());
create policy "Creator delete" on public.raid_items for delete to authenticated using (created_by = auth.uid());
create policy "Creator update" on public.decisions for update to authenticated using (created_by = auth.uid());
create policy "Creator delete" on public.decisions for delete to authenticated using (created_by = auth.uid());
create policy "Creator delete" on public.task_dependencies for delete to authenticated using (created_by = auth.uid());
create policy "Creator delete" on public.task_comments for delete to authenticated using (author_id = auth.uid());

grant select, insert, update, delete on public.raid_items, public.decisions to authenticated;
grant select, insert, delete on public.task_dependencies, public.task_comments to authenticated;
grant select, insert on public.activity_events to authenticated;
grant usage, select on all sequences in schema public to authenticated;

